// Returns a full list of all victory poses available for a fighter (signature + variants + universal)
export function getFighterVictoryPosesList(fighterId: string): VictoryPose[] {
  const charInfo = getFighterVictoryPose(fighterId, fighterId);
  
  const poses: VictoryPose[] = [
    // 1. Signature Character Unique Pose
    {
      id: `${fighterId}_sig_1`,
      fighterId,
      name: charInfo.poseTitle,
      nameJP: charInfo.poseKanji,
      kanjiStamp: charInfo.poseKanji,
      description: charInfo.triumphantAction,
      rarity: 'legendary',
      requiredWins: 0,
      bountyCost: 0,
      quote: charInfo.quoteEN,
      quoteJP: charInfo.quoteJP,
      voiceTextJP: charInfo.voiceTextJP,
      triumphantAction: charInfo.triumphantAction,
      signatureMoveName: charInfo.signatureMoveName,
      animationEffect: charInfo.poseAnimation,
      hakiAuraColor: charInfo.hakiAuraColor,
      badgeEmoji: charInfo.badgeEmoji,
      clipDurationSeconds: 4.5,
      cameraPreset: 'cinematic_zoom',
    },
  ];

  // 2. Add Stance Variants as Unlockables
  if (charInfo.victoryStanceVariants && charInfo.victoryStanceVariants.length > 0) {
    charInfo.victoryStanceVariants.forEach((variantName, idx) => {
      poses.push({
        id: `${fighterId}_variant_${idx + 1}`,
        fighterId,
        name: `${variantName}`,
        nameJP: `${charInfo.poseKanji} • 弐`,
        kanjiStamp: `${charInfo.name.split(' ')[0]}・絶勝`,
        description: `Alternative triumphant stance: ${variantName} celebrating absolute victory on the Grand Line.`,
        rarity: idx === 0 ? 'rare' : 'mythic',
        requiredWins: (idx + 1) * 2,
        bountyCost: (idx + 1) * 10000,
        quote: charInfo.quoteEN,
        quoteJP: charInfo.quoteJP,
        voiceTextJP: charInfo.voiceTextJP,
        triumphantAction: `${variantName} with concentrated spiritual aura and celebratory flares.`,
        signatureMoveName: `${charInfo.signatureMoveName} (Alt Form)`,
        animationEffect: charInfo.poseAnimation,
        hakiAuraColor: charInfo.hakiAuraColor,
        badgeEmoji: charInfo.badgeEmoji,
        clipDurationSeconds: 4.0,
        cameraPreset: idx === 0 ? 'anime_split' : 'wide_stage',
      });
    });
  }

  // 3. Include Universal Poses
  DEFAULT_VICTORY_POSES.forEach((up) => {
    poses.push({
      ...up,
      id: `${fighterId}_${up.id}`,
    });
  });

  return poses;
}

// Fallback generator for custom created fighters or unmapped characters
export function getFighterVictoryPose(fighterId: string, fighterName: string): VictoryPoseInfo {
  if (VICTORY_POSES_DATABASE[fighterId]) {
    return VICTORY_POSES_DATABASE[fighterId];
  }

  // Attempt to match by name keyword
  const nameLower = (fighterName || fighterId || '').toLowerCase();
  for (const key of Object.keys(VICTORY_POSES_DATABASE)) {
    const data = VICTORY_POSES_DATABASE[key];
    if (data.name.toLowerCase().includes(nameLower) || nameLower.includes(data.name.toLowerCase())) {
      return data;
    }
  }

  return {
    fighterId,
    name: fighterName || 'Grand Line Champion',
    poseTitle: 'Grand Line Champion • Triumphant Salute',
    poseKanji: '新時代の覇者・凱歌',
    quoteEN: `Victory is mine! True willpower transcends all obstacles on this sea!`,
    quoteJP: `完全勝利だ！揺るぎなき意志こそが、この海を制する！`,
    voiceTextJP: `かんぜんしょうりだ！ゆるぎなきいしこそが、このうみをせいする！`,
    triumphantAction: 'Strikes an iconic triumphant champion pose, hoisting weapons high amidst golden fireworks and thunderous crowd cheers!',
    signatureMoveName: 'Supreme Willpower Finisher',
    hakiAuraColor: '#f59e0b',
    badgeEmoji: '🏆',
    signatureSound: 'royal',
    poseAnimation: 'conqueror_aura',
    victoryStanceVariants: ['Champion Belt Raise', 'Heroic Battle Cry', 'Supreme Will Salute'],
  };
}
