/**
 * Fallback / dynamic generator for fighters without explicit pre-baked configs (including custom characters)
 */
export function getCharacterAwakeningProfile(fighter: Fighter): AwakeningProfile {
  if (AWAKENING_PROFILES[fighter.id]) {
    return AWAKENING_PROFILES[fighter.id];
  }

  // Generate dynamic tailored awakening profile based on fighting style / affiliation / archetype
  const fruit = fighter.devilFruit;
  const isFruitUser = Boolean(fruit && fruit.type !== 'None (Pure Haki)');
  const isConqueror = fighter.haki.conqueror >= 75;

  let formName = `${fighter.name}: Awakened Will`;
  let formNameJP = `${fighter.japaneseName || fighter.name}：覚醒の極致`;
  let auraColor = fighter.themeColor || '#e11d48';
  let secondaryAuraColor = fighter.secondaryColor || '#881337';
  let auraStyle: AwakeningProfile['auraStyle'] = 'radiant_gold';
  let quote = `I will not fall here! Witness my true power and resolve!`;
  let quoteJP = `ここで倒れるわけにはいかん！我が真なる力を目撃せよ！`;

  if (isFruitUser && fruit) {
    formName = `${fruit.name} (True Awakening)`;
    formNameJP = `${fruit.japaneseName || fruit.name}：神化覚醒`;
    auraColor = '#38bdf8';
    secondaryAuraColor = '#0369a1';
    auraStyle = 'cyan_room';
    quote = `My Devil Fruit powers have reached their ultimate awakened state!`;
    quoteJP = `悪魔の実の能力が究極の覚醒状態に達した！`;
  } else if (isConqueror) {
    formName = `Supreme Sovereign Domain`;
    formNameJP = `覇王色の領域：絶対神威`;
    auraColor = '#ef4444';
    secondaryAuraColor = '#7f1d1d';
    auraStyle = 'conqueror_red';
    quote = `Tremble before the supreme willpower of a true conqueror!`;
    quoteJP = `真の覇王の意思の前にひれ伏すがいい！`;
  }

  const uniqueMove1: Move = {
    id: `${fighter.id}_awakened_move_1`,
    name: `AWAKENED: ${fighter.moves[0]?.name || 'Unleashed Strike'} Prime`,
    nameJP: `覚醒・極大奥義`,
    type: 'awakening',
    baseDamage: Math.round((fighter.stats.attack * 3.8)),
    missRate: 0,
    critBonus: 35,
    meterCost: 1,
    meterGain: 30,
    guardDamage: 80,
    cooldown: 1,
    description: `An awakened empowered strike channeling the fighter's deepest fighting discipline.`,
    element: fruit?.primaryElement || 'Awakened Haki Force',
    hakiInfused: true,
  };

  const uniqueMove2: Move = {
    id: `${fighter.id}_awakened_move_2`,
    name: `AWAKENED: Ultimate ${fighter.epithet || 'Champion'} Cataclysm`,
    nameJP: `覚醒・終焉の破滅撃`,
    type: 'awakening',
    baseDamage: Math.round((fighter.stats.attack * 6.2)),
    missRate: 0,
    critBonus: 50,
    meterCost: 2,
    meterGain: 0,
    guardDamage: 100,
    cooldown: 3,
    description: `A devastating ultimate maneuver that unleashes every ounce of awakened spirit into a game-ending blow.`,
    element: fruit?.primaryElement || 'Supreme Sovereign Finale',
    hakiInfused: true,
  };

  return {
    id: `${fighter.id}_dynamic_awakening`,
    formName,
    formNameJP,
    epithetTitle: (fighter.epithet || 'GRAND LINE LEGEND').toUpperCase(),
    subtitle: `${fighter.name} taps into their latent potential, awakening supreme combat stats!`,
    auraColor,
    secondaryAuraColor,
    auraStyle,
    statBuffs: {
      attackMultiplier: 1.35,
      defenseMultiplier: 1.25,
      speedMultiplier: 1.30,
      critBonus: 30,
      staminaRegenMultiplier: 2.2,
    },
    transformationQuote: quote,
    transformationQuoteJP: quoteJP,
    uniqueMoves: [uniqueMove1, uniqueMove2],
  };
}
